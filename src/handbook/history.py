"""Create immutable, language-specific edition snapshots without changing checkout."""

import argparse
import datetime
import os
from pathlib import Path
import re
import subprocess
import tempfile
from urllib.parse import quote

from . import const
from .preservation import content_hash, read_json


def git(root, *args, data=None, env=None, check=True):
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        input=data,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
    )
    if check and result.returncode:
        raise RuntimeError(result.stderr.decode().strip())
    return result.stdout.decode().strip() if result.returncode == 0 else None


def edition_directories(root, language):
    base = root / "editions" if language == "eng" else root / "editions" / language
    if not base.exists():
        return []
    return sorted(
        p for p in base.iterdir() if p.is_dir() and re.fullmatch(r"\d{4}-\d{2}", p.name)
    )


def snapshots(root, language):
    for directory in edition_directories(root, language):
        datetime.datetime.strptime(directory.name, "%Y-%m")
        files = [directory / f"{page}.md" for page in const.PAGES]
        if not all(p.is_file() for p in files):
            print(f"Skipping incomplete edition: {language}/{directory.name}")
            continue
        sources = read_json(directory / "sources.json")
        for file in files:
            if language == "por" or file.stem in sources:
                source = sources.get(file.stem, {})
                if (
                    source.get("language") != language
                    or source.get("edition") != directory.name
                    or source.get("content_sha256")
                    != content_hash(file.read_text(encoding="utf8"))
                ):
                    raise ValueError(
                        f"Unverified source: {language}/{directory.name}/{file.name}"
                    )
        yield directory, files


def snapshot_tree(root, files, index):
    env = {**os.environ, "GIT_INDEX_FILE": str(index)}
    git(root, "read-tree", "--empty", env=env)
    entries = []
    for file in files:
        # Match the original comparison script, but only in the generated snapshot.
        text = re.sub(
            r"\[(.*?)\]\((.*?)\)",
            lambda m: f"[{m[1].strip()}]",
            file.read_text(encoding="utf8"),
        )
        blob = git(root, "hash-object", "-w", "--stdin", data=text.encode("utf8"))
        entries.append(f"100644 {blob}\thandbook/{file.name}\n")
    git(root, "update-index", "--index-info", env=env, data="".join(entries).encode())
    return git(root, "write-tree", env=env)


def comparison_index(language, dates, repository):
    title = "Edições em português" if language == "por" else "English editions"
    text = [
        f"# {title}",
        "",
        "Generated by `branch.sh`. Links become available after publishing the tags.",
        "Snapshots contain chapter Markdown only; capture evidence remains in each dated edition's `sources.json`.",
        "",
        "| Edition | Tag | Previous edition | Latest edition |",
        "| --- | --- | --- | --- |",
    ]
    if not dates:
        return "\n".join(text) + "\n"
    latest = dates[-1]
    for i in reversed(range(len(dates))):
        date = dates[i]
        tag = f"{language}/{date}"
        link = f"https://github.com/{repository}/tree/{quote(tag, safe='')}/handbook"

        def compare(old, new):
            return f"[Compare](https://github.com/{repository}/compare/{quote(language + '/' + old, safe='')}..{quote(language + '/' + new, safe='')})"

        previous = compare(dates[i - 1], date) if i else "—"
        current = compare(date, latest) if date != latest else "—"
        text.append(f"| {date} | [{tag}]({link}) | {previous} | {current} |")
    text += [
        "",
        "Two-dot comparisons compare the tagged snapshots directly, including editions recovered out of order.",
        "Legacy English tags without a language prefix are preserved unchanged.",
    ]
    return "\n".join(text) + "\n"


def build_history(root, languages, repository, dry_run=False):
    root = Path(root).resolve()
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("--repository must be OWNER/REPO")
    commands = []
    indexes = {}
    with tempfile.TemporaryDirectory(prefix="handbook-index-") as temporary:
        for language in languages:
            branch = f"refs/heads/diff-{language}"
            old_head = git(root, "rev-parse", "--verify", branch, check=False)
            parent = old_head
            dates = []
            for directory, files in snapshots(root, language):
                tree = snapshot_tree(root, files, Path(temporary) / "index")
                date = directory.name
                tag = f"{language}/{date}"
                ref = f"refs/tags/{tag}"
                existing = git(
                    root, "rev-parse", "--verify", ref + "^{commit}", check=False
                )
                if existing:
                    if git(root, "rev-parse", ref + "^{tree}") != tree:
                        raise ValueError(
                            f"Refusing to change immutable tag {tag}; the edition content differs"
                        )
                    if (
                        parent
                        and git(
                            root,
                            "merge-base",
                            "--is-ancestor",
                            existing,
                            parent,
                            check=False,
                        )
                        is None
                    ):
                        raise ValueError(
                            f"Tag {tag} is not in {branch}; fetch its history before continuing"
                        )
                    if not parent:
                        raise ValueError(
                            f"Tag {tag} exists without {branch}; fetch the comparison branch"
                        )
                else:
                    args = ["commit-tree", tree]
                    if parent:
                        args.extend(["-p", parent])
                    commit = git(
                        root,
                        *args,
                        data=f"Add {language} handbook edition {date}\n".encode(),
                    )
                    identity = git(root, "var", "GIT_COMMITTER_IDENT")
                    tag_object = git(
                        root,
                        "mktag",
                        data=(
                            f"object {commit}\ntype commit\ntag {tag}\n"
                            f"tagger {identity}\n\nOfficial handbook: {language} {date}\n"
                        ).encode(),
                    )
                    commands.append(f"create {ref} {tag_object}")
                    parent = commit
                    print(
                        f"{'Would create' if dry_run else 'Prepared'} {tag}: {commit[:12]}"
                    )
                dates.append(date)
            if parent != old_head:
                commands.append(
                    f"update {branch} {parent} {old_head}"
                    if old_head
                    else f"create {branch} {parent}"
                )
            indexes[language] = comparison_index(language, dates, repository)
        if dry_run:
            return
        if commands:
            # All tags are create-only; concurrent edits or a conflict abort the whole transaction.
            git(
                root,
                "update-ref",
                "--stdin",
                data=("start\n" + "\n".join(commands) + "\nprepare\ncommit\n").encode(),
            )
        (root / "docs").mkdir(exist_ok=True)
        for language, text in indexes.items():
            (root / "docs" / f"comparisons-{language}.md").write_text(
                text, encoding="utf8"
            )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "language", choices=[*const.LANGUAGES, "all"], nargs="?", default="all"
    )
    parser.add_argument(
        "--repository", required=True, help="GitHub OWNER/REPO for comparison links"
    )
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    root = Path(git(Path.cwd(), "rev-parse", "--show-toplevel"))
    languages = const.LANGUAGES if args.language == "all" else [args.language]
    try:
        build_history(root, languages, args.repository, args.dry_run)
    except (ValueError, RuntimeError) as error:
        parser.exit(1, f"{error}\n")
